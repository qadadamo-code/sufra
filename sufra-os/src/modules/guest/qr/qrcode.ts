/**
 * Minimal QR Code encoder (ISO/IEC 18004, byte mode, versions 1–40, all ECC levels) — no dependency.
 * Follows the structure of Project Nayuki's reference implementation (MIT). Used for the printable
 * table tent cards; output is a boolean module matrix (true = dark).
 *
 *   const qr = encodeQr("https://sufra.app/app/r/sufra-zamalek/t/ZM05", "M");
 *   qr.size, qr.modules[y][x]
 */
export type Ecc = "L" | "M" | "Q" | "H";

const ECC_ORDINAL: Record<Ecc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECC_FORMAT: Record<Ecc, number> = { L: 1, M: 0, Q: 3, H: 2 };

// prettier-ignore
